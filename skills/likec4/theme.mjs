#!/usr/bin/env node
// Prints a LikeC4 specification in a look's colours: `node theme.mjs <look> > spec.c4`.
// Reads ../<look>/tokens.css directly, so a token change reaches diagrams without a copy to update.
// LikeC4 custom colours take one hex value for both themes, so the light tokens are used:
// they are the ones tuned for white text on a filled box.
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));

export function lookTokens(look) {
  const css = readFileSync(join(here, "..", look, "tokens.css"), "utf8");
  const light = css.match(/:root\s*\{([^}]*)\}/)[1];
  const tokens = {};
  for (const [, name, value] of light.matchAll(/--pa-([a-z0-9-]+):\s*([^;]+);/g)) tokens[name] = value.trim();
  return tokens;
}

// Apple's text tokens are translucent rgba(); a box fill has to be opaque, so blend over the page background.
function opaque(value, bg) {
  if (/^#[0-9a-f]{6}$/i.test(value)) return value;
  const m = value.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/);
  if (!m || !/^#[0-9a-f]{6}$/i.test(bg)) throw new Error(`cannot turn ${value} into an opaque hex colour`);
  const a = m[4] === undefined ? 1 : Number(m[4]);
  const under = [1, 3, 5].map(i => parseInt(bg.slice(i, i + 2), 16));
  return "#" + [1, 2, 3].map((i, j) => Math.round(Number(m[i]) * a + under[j] * (1 - a)).toString(16).padStart(2, "0")).join("");
}

export function spec(look) {
  const t = lookTokens(look);
  // LikeC4 1.60 misreads some hex literals ("#008932 must be 3, 6 or 8 characters"), so emit rgba().
  for (const k of ["cat-1", "cat-2", "cat-3", "cat-4", "text-2"]) {
    const hex = opaque(t[k] ?? "", t.bg);
    t[k] = `rgba(${[1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)).join(",")},1)`;
  }
  return `// Generated by polished-artifacts:likec4 theme.mjs for the ${look} look. Regenerate, don't edit.
specification {
  color pa-worker ${t["cat-1"]}
  color pa-service ${t["cat-2"]}
  color pa-person ${t["cat-3"]}
  color pa-bus ${t["cat-4"]}
  color pa-store ${t["text-2"]}

  element actor {
    notation 'Person'
    style { shape person; color pa-person; size sm }
  }
  element system {
    style { color pa-store; opacity 4%; padding xl }
  }
  element layer {
    style { color pa-store; opacity 6%; border dotted; padding lg }
  }
  element service {
    notation 'Service'
    style { color pa-service; size md; sizing fixed; iconPosition left }
  }
  element webapp {
    notation 'Web app'
    style { shape browser; color pa-service; size md; sizing fixed; iconPosition left }
  }
  element worker {
    notation 'Worker'
    style { color pa-worker; size md; sizing fixed; iconPosition left }
  }
  element bus {
    notation 'Queue or workflow bus'
    style { shape queue; color pa-bus; size md; sizing fixed; iconPosition left }
  }
  element store {
    notation 'Data store'
    style { shape storage; color pa-store; size md; sizing fixed; iconPosition left }
  }
  element external {
    notation 'External service'
    style { color muted; size sm; sizing fixed; iconPosition left }
  }

  relationship sync {
    notation 'Synchronous call'
    color pa-service
    line solid
  }
  relationship async {
    notation 'Async message'
    color pa-bus
    line dashed
  }
  relationship data {
    notation 'Data access'
    color pa-store
    line dotted
  }
  relationship ext {
    notation 'Third-party API'
    color muted
    line solid
  }
  relationship planned {
    notation 'Planned'
    color gray
    line dotted
  }

  tag planned
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const look = process.argv[2];
  if (!look) {
    console.error("usage: node theme.mjs <look>");
    process.exit(2);
  }
  process.stdout.write(spec(look));
}
